export const DEFAULT_PHILOSOPHY = "citelcoach";
export const normalizePhilosophy = (id) =>
  philosophies.some((p) => p.id === id) ? id : DEFAULT_PHILOSOPHY;
export const philosophyById = (id) =>
  philosophies.find((p) => p.id === normalizePhilosophy(id));
export const principleById = (philosophy, id) =>
  philosophyById(philosophy).principles.find((p) => p.id === id);
